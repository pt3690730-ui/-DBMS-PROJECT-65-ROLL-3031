--               Ticket Booking
-- ----------------------------------------------------------------------------
--  This file is a PURE CREATE script. It can be applied to any schema:
--      search_path -> <target schema>, public, extensions
--  All 17 tables are created in strict 3NF except for two documented,
--  deliberate denormalisations (see section 9 - DESIGN NOTES):
--      * screening.end_time         - stored so that ex_screening_no_overlap
--                                     (an EXCLUDE constraint) can be declarative
--      * booked_seat.screening_id   - repeated so that ux_active_seat can be a
--                                     declarative partial unique index; kept
--                                     consistent by a composite foreign key
-- ----------------------------------------------------------------------------
--  Everything that protects the data lives HERE, inside the database:
--      17 tables      12 CHECK constraints on business values
--      8 indexes      5 triggers (T1..T5)   3 functions   6 views
--      Row Level Security ON for all 17 tables, with NO public policies.
-- ============================================================================

CREATE EXTENSION IF NOT EXISTS btree_gist;   -- needed by ex_screening_no_overlap

-- ============================================================================
-- SECTION 0 - CLOCK
-- fn_now() returns the "current" timestamp. The application may pin it with
--      SET cinema.now = 'YYYY-MM-DD HH:MM';
-- so that the whole booking / cancellation / refund logic can be demonstrated
-- and tested against a fixed clock (CINEMA_NOW). Without it, fn_now() = now().
-- ============================================================================
CREATE OR REPLACE FUNCTION fn_now()
RETURNS TIMESTAMP
LANGUAGE sql STABLE AS $$
    SELECT COALESCE(NULLIF(current_setting('cinema.now', true), '')::timestamp,
                    now()::timestamp)
$$;

COMMENT ON FUNCTION fn_now() IS
'Application clock. Honours the per-session setting cinema.now, else now().';

