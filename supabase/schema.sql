-- 1 -------------------------------------------------------------- cinema ----
CREATE TABLE cinema (
    cinema_id    INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cinema_name  TEXT         NOT NULL CHECK (length(trim(cinema_name)) >= 3),
    city         TEXT         NOT NULL CHECK (length(trim(city)) >= 2),
    address      TEXT         NOT NULL CHECK (length(trim(address)) >= 5),
    phone        VARCHAR(15)  NOT NULL CHECK (phone ~ '^[0-9]{10,15}$'),
    CONSTRAINT ux_cinema_name_city UNIQUE (cinema_name, city)
);
COMMENT ON TABLE cinema IS 'A physical multiplex. UNIQUE(cinema_name, city) stops the same cinema being entered twice in a city.';

-- 2 -------------------------------------------------------------- screen ----
CREATE TABLE screen (
    screen_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cinema_id    INTEGER NOT NULL REFERENCES cinema(cinema_id) ON DELETE RESTRICT,
    screen_name  TEXT    NOT NULL CHECK (length(trim(screen_name)) >= 1),
    screen_type  TEXT    NOT NULL CHECK (screen_type IN ('2D','3D','IMAX','4DX')),
    CONSTRAINT ux_screen_name UNIQUE (cinema_id, screen_name)
);
COMMENT ON TABLE screen IS 'An auditorium inside a cinema. A cinema cannot have two screens with the same name.';

-- 3 ---------------------------------------------------------------- seat ----
CREATE TABLE seat (
    seat_id    INTEGER  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    screen_id  INTEGER  NOT NULL REFERENCES screen(screen_id) ON DELETE CASCADE,
    row_label  CHAR(1)  NOT NULL CHECK (row_label ~ '^[A-Z]$'),
    seat_no    SMALLINT NOT NULL CHECK (seat_no > 0),
    seat_type  TEXT     NOT NULL CHECK (seat_type IN ('STANDARD','PREMIUM','RECLINER')),
    CONSTRAINT ux_seat_position UNIQUE (screen_id, row_label, seat_no)
);
COMMENT ON TABLE seat IS 'Seat inventory. Deleting a screen cascades to its seats (ON DELETE CASCADE) - the only cascade in the schema.';

-- 4 --------------------------------------------------------------- movie ----
CREATE TABLE movie (
    movie_id     INTEGER  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        TEXT     NOT NULL CHECK (length(trim(title)) >= 1),
    genre        TEXT     NOT NULL,
    language     TEXT     NOT NULL,
    duration_min SMALLINT NOT NULL CHECK (duration_min > 0 AND duration_min <= 400),
    certificate  TEXT     NOT NULL CHECK (certificate IN ('U','UA','A','S')),
    release_date DATE     NOT NULL,
    CONSTRAINT ux_movie_identity UNIQUE (title, language, release_date)
);
COMMENT ON TABLE movie IS 'Movie master data. A title may be re-released in a different language or on a new date.';

-- 5 ----------------------------------------------------------- screening ----
CREATE TABLE screening (
    screening_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id     INTEGER NOT NULL REFERENCES movie(movie_id)   ON DELETE RESTRICT,
    screen_id    INTEGER NOT NULL REFERENCES screen(screen_id) ON DELETE RESTRICT,
    start_time   TIMESTAMP NOT NULL,
    end_time     TIMESTAMP NOT NULL,
    base_price   NUMERIC(8,2) NOT NULL CHECK (base_price > 0),
    status       TEXT NOT NULL DEFAULT 'SCHEDULED'
                 CHECK (status IN ('SCHEDULED','CANCELLED','COMPLETED')),
    CONSTRAINT ck_screening_time CHECK (end_time > start_time),
    CONSTRAINT ux_screening_slot UNIQUE (screen_id, start_time),
    -- A screen can never run two shows at the same time. The tsrange is [start,
    -- end) so back-to-back shows are allowed, and the 15 minute cleaning gap
    -- baked into end_time keeps even those apart. Cancelled shows free the slot.
    CONSTRAINT ex_screening_no_overlap EXCLUDE USING gist (
        screen_id WITH =,
        tsrange(start_time, end_time) WITH &&
    ) WHERE (status <> 'CANCELLED')
);
COMMENT ON TABLE screening IS 'A show of a movie on a screen at a time. end_time = start_time + duration + 15 min cleaning gap.';
COMMENT ON COLUMN screening.end_time IS 'Stored (not computed) on purpose: an EXCLUDE constraint needs a real column. Documented denormalisation #1.';

-- 6 ------------------------------------------------------------ customer ----
CREATE TABLE customer (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   TEXT    NOT NULL CHECK (length(trim(full_name)) BETWEEN 2 AND 80),
    email       TEXT    NOT NULL UNIQUE
                CHECK (email ~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'),
    phone       VARCHAR(15) NOT NULL CHECK (phone ~ '^[0-9]{10,15}$'),
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);
COMMENT ON TABLE customer IS 'Cinema patrons. customer_id = 1 is the shared "Walk-in Guest" used for counter sales.';

-- 7 --------------------------------------------------------------- staff ----
CREATE TABLE staff (
    staff_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cinema_id     INTEGER NOT NULL REFERENCES cinema(cinema_id) ON DELETE RESTRICT,
    full_name     TEXT    NOT NULL,
    username      TEXT    NOT NULL UNIQUE,
    password_hash TEXT    NOT NULL,
    role          TEXT    NOT NULL CHECK (role IN ('ADMIN','BOX_OFFICE'))
);
COMMENT ON TABLE staff IS 'Box-office and admin users. Only the hash of a password is ever stored.';

-- 8 --------------------------------------------------- concession_item -----
CREATE TABLE concession_item (
    item_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name  TEXT    NOT NULL UNIQUE,
    category   TEXT    NOT NULL CHECK (category IN ('POPCORN','BEVERAGE','SNACK','COMBO')),
    unit_price NUMERIC(8,2) NOT NULL CHECK (unit_price > 0),
    stock_qty  INTEGER NOT NULL CHECK (stock_qty >= 0)
