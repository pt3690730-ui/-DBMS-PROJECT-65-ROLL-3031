-- 5.1 -------------------------------------------------- v_show_occupancy ---
CREATE OR REPLACE VIEW v_show_occupancy AS
SELECT s.screening_id,
       m.title                AS movie,
       m.language,
       m.certificate,
       ci.cinema_name,
       sc.screen_name,
       sc.screen_type,
       s.start_time,
       s.end_time,
       s.status,
       s.base_price,
       (SELECT count(*) FROM seat st WHERE st.screen_id = s.screen_id) AS total_seats,
       COALESCE(bs.booked, 0)                                          AS booked_seats,
       (SELECT count(*) FROM seat st WHERE st.screen_id = s.screen_id)
           - COALESCE(bs.booked, 0)                                    AS seats_left,
       ROUND(100.0 * COALESCE(bs.booked, 0)
             / NULLIF((SELECT count(*) FROM seat st WHERE st.screen_id = s.screen_id), 0), 1)
                                                                       AS occupancy_pct
FROM screening s
JOIN movie  m  ON m.movie_id  = s.movie_id
JOIN screen sc ON sc.screen_id = s.screen_id
JOIN cinema ci ON ci.cinema_id = sc.cinema_id
LEFT JOIN (SELECT screening_id, count(*) AS booked
             FROM booked_seat WHERE status = 'BOOKED'
            GROUP BY screening_id) bs ON bs.screening_id = s.screening_id
ORDER BY s.start_time;

-- 5.2 ---------------------------------------------- v_movie_performance -----
CREATE OR REPLACE VIEW v_movie_performance AS
SELECT m.movie_id,
       m.title,
       m.language,
       m.certificate,
       m.duration_min,
       count(DISTINCT s.screening_id)                     AS screenings,
       COALESCE(sum(t.tickets), 0)                        AS tickets_sold,
       COALESCE(sum(t.revenue), 0)::numeric(12,2)         AS ticket_revenue,
       ROUND(avg(o.occupancy_pct), 1)                     AS avg_occupancy_pct
FROM movie m
LEFT JOIN screening s ON s.movie_id = m.movie_id
LEFT JOIN (SELECT tb.screening_id,
                  count(*) AS tickets,
                  sum(tk.price) AS revenue
             FROM ticket tk
             JOIN booked_seat tb ON tb.booked_seat_id = tk.booked_seat_id
            WHERE tk.status <> 'VOID'
            GROUP BY tb.screening_id) t ON t.screening_id = s.screening_id
LEFT JOIN v_show_occupancy o ON o.screening_id = s.screening_id
GROUP BY m.movie_id, m.title, m.language, m.certificate, m.duration_min
ORDER BY ticket_revenue DESC;

-- 5.3 --------------------------------------------- v_screen_utilization -----
CREATE OR REPLACE VIEW v_screen_utilization AS
SELECT sc.screen_id,
       ci.cinema_name,
       sc.screen_name,
       sc.screen_type,
       (SELECT count(*) FROM seat st WHERE st.screen_id = sc.screen_id) AS seats,
       count(DISTINCT s.screening_id)                                   AS screenings,
       COALESCE(sum(bs.booked), 0)                                      AS seats_sold,
       ROUND(100.0 * COALESCE(sum(bs.booked), 0)
             / NULLIF(count(DISTINCT s.screening_id)
                      * (SELECT count(*) FROM seat st WHERE st.screen_id = sc.screen_id), 0), 1)
                                                                        AS utilization_pct
FROM screen sc
JOIN cinema ci ON ci.cinema_id = sc.cinema_id
LEFT JOIN screening s ON s.screen_id = sc.screen_id AND s.status <> 'CANCELLED'
LEFT JOIN (SELECT screening_id, count(*) AS booked
             FROM booked_seat WHERE status = 'BOOKED'
            GROUP BY screening_id) bs ON bs.screening_id = s.screening_id
GROUP BY sc.screen_id, ci.cinema_name, sc.screen_name, sc.screen_type
ORDER BY utilization_pct DESC NULLS LAST;

-- 5.4 ---------------------------------------------- v_concession_sales ------
CREATE OR REPLACE VIEW v_concession_sales AS
SELECT i.item_id,
       i.item_name,
       i.category,
       i.unit_price,
       i.stock_qty,
       COALESCE(sum(x.quantity), 0)                                  AS units_sold,
       COALESCE(sum(x.quantity * x.unit_price), 0)::numeric(12,2)    AS revenue,
       count(DISTINCT x.order_id)                                    AS orders
FROM concession_item i
LEFT JOIN (SELECT oi.item_id, oi.quantity, oi.unit_price, oi.order_id
             FROM order_item oi
             JOIN concession_order o ON o.order_id = oi.order_id
            WHERE o.status = 'PLACED') x ON x.item_id = i.item_id
GROUP BY i.item_id, i.item_name, i.category, i.unit_price, i.stock_qty
ORDER BY revenue DESC;

-- 5.5 -------------------------------------------- v_cancellation_summary ----
CREATE OR REPLACE VIEW v_cancellation_summary AS
SELECT c.cancellation_id,
       b.booking_id,
       cu.full_name                                    AS customer,
       m.title                                         AS movie,
       s.start_time                                    AS show_time,
       c.cancelled_at,
       c.cancelled_by,
       c.reason,
       COALESCE(p.amount, 0)::numeric(12,2)            AS amount_paid,
       COALESCE(r.total_refund, 0)::numeric(12,2)      AS refund_amount,
       ROUND(100.0 * COALESCE(r.total_refund, 0) / NULLIF(p.amount, 0), 1) AS refund_pct,
       COALESCE(r.status, 'NONE')                      AS refund_status
FROM cancellation c
JOIN booking  b  ON b.booking_id   = c.booking_id
JOIN customer cu ON cu.customer_id = b.customer_id
JOIN screening s ON s.screening_id = b.screening_id
JOIN movie    m  ON m.movie_id     = s.movie_id
LEFT JOIN LATERAL (
    SELECT sum(pay.amount) AS amount
      FROM payment pay
     WHERE pay.booking_id = b.booking_id AND pay.status <> 'FAILED'
) p ON true
LEFT JOIN LATERAL (
    SELECT sum(rf.refund_amount) AS total_refund, max(rf.refund_status) AS status
      FROM refund rf
     WHERE rf.cancellation_id = c.cancellation_id
) r ON true
ORDER BY c.cancelled_at DESC;

-- 5.6 ------------------------------------------------ v_daily_revenue -------
CREATE OR REPLACE VIEW v_daily_revenue AS
WITH days AS (
    SELECT paid_at::date AS day FROM payment WHERE booking_id IS NOT NULL
    UNION
    SELECT paid_at::date         FROM payment WHERE order_id  IS NOT NULL
    UNION
    SELECT refunded_at::date     FROM refund
    UNION
    SELECT start_time::date      FROM screening
), agg AS (
    SELECT d.day,
           (SELECT COALESCE(sum(amount), 0) FROM payment p
             WHERE p.booking_id IS NOT NULL AND p.status <> 'FAILED'
               AND p.paid_at::date = d.day)                AS tickets,
           (SELECT COALESCE(sum(amount), 0) FROM payment p
             WHERE p.order_id IS NOT NULL AND p.status <> 'FAILED'
               AND p.paid_at::date = d.day)                AS concessions,
           (SELECT COALESCE(sum(refund_amount), 0) FROM refund r
             WHERE r.refunded_at::date = d.day)            AS refunds
      FROM days d
)
SELECT day,
       tickets::numeric(12,2)                                       AS ticket_revenue,
       concessions::numeric(12,2)                                   AS concession_revenue,
       refunds::numeric(12,2)                                       AS refunds,
       (tickets + concessions - refunds)::numeric(12,2)             AS net_revenue
FROM agg
ORDER BY day;

