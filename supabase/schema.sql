-- 3.1 ------------------------------------------------- fn_schedule_screening
-- Creates a show; end_time is derived from the movie duration + 15 min gap.
CREATE OR REPLACE FUNCTION fn_schedule_screening(
    p_movie_id  INTEGER,
    p_screen_id INTEGER,
    p_start     TIMESTAMP,
    p_base_price NUMERIC DEFAULT 150.00
) RETURNS screening
LANGUAGE plpgsql AS $$
DECLARE
    v_duration SMALLINT;
    v_row      screening;
BEGIN
    SELECT duration_min INTO v_duration FROM movie WHERE movie_id = p_movie_id;
    IF v_duration IS NULL THEN
        RAISE EXCEPTION 'Movie % does not exist', p_movie_id;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM screen WHERE screen_id = p_screen_id) THEN
        RAISE EXCEPTION 'Screen % does not exist', p_screen_id;
    END IF;
    IF p_base_price IS NULL OR p_base_price <= 0 THEN
        RAISE EXCEPTION 'Base price must be greater than 0 (got %)', p_base_price;
    END IF;
    IF p_start <= fn_now() THEN
        RAISE EXCEPTION 'A show can only be scheduled in the future: % is not after %',
            to_char(p_start, 'DD Mon YYYY HH24:MI'), to_char(fn_now(), 'DD Mon YYYY HH24:MI');
    END IF;

    INSERT INTO screening (movie_id, screen_id, start_time, end_time, base_price)
    VALUES (p_movie_id, p_screen_id, p_start,
            p_start + make_interval(mins => v_duration + 15), p_base_price)
    RETURNING * INTO v_row;
    RETURN v_row;
END $$;

-- 3.2 ------------------------------------------------------------ fn_seat_id
-- Human seat reference "row + number" -> surrogate seat_id, with a clear error.
CREATE OR REPLACE FUNCTION fn_seat_id(
    p_screen_id INTEGER,
    p_row       TEXT,
    p_seat_no   INTEGER
) RETURNS INTEGER
LANGUAGE plpgsql STABLE AS $$
DECLARE
    v_seat_id INTEGER;
BEGIN
    SELECT seat_id INTO v_seat_id
      FROM seat
     WHERE screen_id = p_screen_id
       AND row_label = upper(trim(p_row))
       AND seat_no   = p_seat_no;
    IF v_seat_id IS NULL THEN
        RAISE EXCEPTION 'No seat %-% exists on screen %',
            upper(trim(p_row)), p_seat_no, p_screen_id;
    END IF;
    RETURN v_seat_id;
END $$;

-- 3.3 ----------------------------------------------------- fn_refund_percent
-- Picks the cancellation policy row with the largest min_hours_before that is
-- still <= the hours between the cancellation instant and the show.
CREATE OR REPLACE FUNCTION fn_refund_percent(
    p_booking_id INTEGER,
    p_at_time    TIMESTAMP DEFAULT fn_now()
) RETURNS SMALLINT
LANGUAGE plpgsql STABLE AS $$
DECLARE
    v_start TIMESTAMP;
    v_hours NUMERIC;
    v_pct   SMALLINT;
BEGIN
    SELECT s.start_time INTO v_start
      FROM booking b
      JOIN screening s ON s.screening_id = b.screening_id
     WHERE b.booking_id = p_booking_id;
    IF v_start IS NULL THEN
        RAISE EXCEPTION 'Booking % does not exist', p_booking_id;
    END IF;

    v_hours := EXTRACT(EPOCH FROM (v_start - p_at_time)) / 3600.0;

    SELECT refund_percent INTO v_pct
      FROM cancellation_policy
     WHERE min_hours_before <= v_hours
     ORDER BY min_hours_before DESC
     LIMIT 1;

    RETURN COALESCE(v_pct, 0);      -- show already started / no tier matched
END $$;

