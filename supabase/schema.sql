-- T1 ------------------------------- a booked seat must really be bookable ---
CREATE OR REPLACE FUNCTION fn_validate_booked_seat()
RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    v_screen_of_show INTEGER;
    v_show_status    TEXT;
    v_show_start     TIMESTAMP;
    v_screen_of_seat INTEGER;
    v_row            CHAR(1);
    v_no             SMALLINT;
BEGIN
    SELECT sc.screen_id, sc.status, sc.start_time
      INTO v_screen_of_show, v_show_status, v_show_start
      FROM screening sc
     WHERE sc.screening_id = NEW.screening_id;
    IF v_screen_of_show IS NULL THEN
        RAISE EXCEPTION 'Screening % does not exist', NEW.screening_id;
    END IF;

    SELECT st.screen_id, st.row_label, st.seat_no
      INTO v_screen_of_seat, v_row, v_no
      FROM seat st
     WHERE st.seat_id = NEW.seat_id;
    IF v_screen_of_seat IS NULL THEN
        RAISE EXCEPTION 'Seat % does not exist', NEW.seat_id;
    END IF;

    IF v_screen_of_seat <> v_screen_of_show THEN
        RAISE EXCEPTION 'Seat %-% belongs to screen %, but screening % runs on screen %',
            v_row, v_no, v_screen_of_seat, NEW.screening_id, v_screen_of_show;
    END IF;

    IF NEW.status = 'BOOKED' THEN
        IF v_show_status <> 'SCHEDULED' THEN
            RAISE EXCEPTION 'This show is % - seats can no longer be booked for it', v_show_status;
        END IF;
        IF v_show_start <= fn_now() THEN
            RAISE EXCEPTION 'This show started at % - booking is closed',
                to_char(v_show_start, 'DD Mon YYYY HH24:MI');
        END IF;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_booked_seat_validate
    BEFORE INSERT OR UPDATE ON booked_seat
    FOR EACH ROW EXECUTE FUNCTION fn_validate_booked_seat();

-- T2 ----------------------------- only a live confirmed show may be cancelled
CREATE OR REPLACE FUNCTION fn_validate_cancellation()
RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    v_status TEXT;
    v_start  TIMESTAMP;
BEGIN
    SELECT b.status, s.start_time
      INTO v_status, v_start
      FROM booking b
      JOIN screening s ON s.screening_id = b.screening_id
     WHERE b.booking_id = NEW.booking_id;
    IF v_status IS NULL THEN
        RAISE EXCEPTION 'Booking % does not exist', NEW.booking_id;
    END IF;
    IF v_status <> 'CONFIRMED' THEN
        RAISE EXCEPTION 'Booking % is already % - it cannot be cancelled twice',
            NEW.booking_id, v_status;
    END IF;
    IF v_start <= fn_now() THEN
        RAISE EXCEPTION 'The show started at % - this booking can no longer be cancelled',
            to_char(v_start, 'DD Mon YYYY HH24:MI');
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_cancellation_validate
    BEFORE INSERT OR UPDATE ON cancellation
    FOR EACH ROW EXECUTE FUNCTION fn_validate_cancellation();

-- T3 ---------------------------- cancelling a booking frees everything it held
CREATE OR REPLACE FUNCTION fn_apply_cancellation()
RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    v_tickets INTEGER;
    v_seats   INTEGER;
BEGIN
    UPDATE booking SET status = 'CANCELLED' WHERE booking_id = NEW.booking_id;

    UPDATE ticket t
       SET status = 'VOID'
      FROM booked_seat bs
     WHERE bs.booked_seat_id = t.booked_seat_id
       AND bs.booking_id = NEW.booking_id
       AND t.status = 'ISSUED';
    GET DIAGNOSTICS v_tickets = ROW_COUNT;

    UPDATE booked_seat bs
       SET status = 'RELEASED'
     WHERE bs.booking_id = NEW.booking_id
       AND bs.status = 'BOOKED';
    GET DIAGNOSTICS v_seats = ROW_COUNT;

    RAISE NOTICE 'Cancellation %: booking % -> CANCELLED, % ticket(s) -> VOID, % seat(s) -> RELEASED',
        NEW.cancellation_id, NEW.booking_id, v_tickets, v_seats;
    RETURN NULL;
END $$;

CREATE TRIGGER trg_cancellation_apply
    AFTER INSERT ON cancellation
    FOR EACH ROW EXECUTE FUNCTION fn_apply_cancellation();

-- T4 ------------------------- a refund can never exceed the policy allowance --
CREATE OR REPLACE FUNCTION fn_validate_refund()
RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    v_booking_id   INTEGER;
    v_cancelled_at TIMESTAMP;
    v_paid         NUMERIC(10,2);
    v_percent      SMALLINT;
    v_limit        NUMERIC(10,2);
    v_previous     NUMERIC(10,2);
BEGIN
    SELECT c.booking_id, c.cancelled_at
      INTO v_booking_id, v_cancelled_at
      FROM cancellation c
     WHERE c.cancellation_id = NEW.cancellation_id;
    IF v_booking_id IS NULL THEN
        RAISE EXCEPTION 'Cancellation % does not exist', NEW.cancellation_id;
    END IF;

    SELECT p.amount INTO v_paid
      FROM payment p
     WHERE p.payment_id = NEW.payment_id
       AND p.booking_id = v_booking_id
       AND p.status <> 'FAILED';
    IF v_paid IS NULL THEN
        RAISE EXCEPTION 'Payment % is not a successful payment of booking %',
            NEW.payment_id, v_booking_id;
    END IF;

    v_percent := fn_refund_percent(v_booking_id, v_cancelled_at);
    v_limit   := round(v_paid * v_percent / 100.0, 2);

    SELECT COALESCE(SUM(r.refund_amount), 0) INTO v_previous
      FROM refund r
     WHERE r.cancellation_id = NEW.cancellation_id;

    IF v_previous + NEW.refund_amount > v_limit THEN
        -- format() instead of RAISE placeholders: '%%' stays a literal % sign
        RAISE EXCEPTION USING MESSAGE = format(
            'Refund limit exceeded: at cancellation time the policy allowed %s%% of the paid amount INR %s (limit INR %s). INR %s is already refunded, so at most INR %s can still be refunded - requested INR %s.',
            v_percent, v_paid, v_limit, v_previous,
            GREATEST(v_limit - v_previous, 0), NEW.refund_amount);
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_refund_validate
    BEFORE INSERT OR UPDATE ON refund
    FOR EACH ROW EXECUTE FUNCTION fn_validate_refund();

-- T5 -------------------- line price from the item master + stock consumption --
CREATE OR REPLACE FUNCTION fn_order_item_stock()
RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    v_price NUMERIC(8,2);
    v_name  TEXT;
    v_stock INTEGER;
BEGIN
    SELECT i.unit_price, i.item_name, i.stock_qty
      INTO v_price, v_name, v_stock
      FROM concession_item i
     WHERE i.item_id = NEW.item_id;
    IF v_price IS NULL THEN
        RAISE EXCEPTION 'Concession item % does not exist', NEW.item_id;
    END IF;

    IF NEW.unit_price IS NULL THEN
        NEW.unit_price := v_price;                 -- default from the item master
    END IF;

    IF v_stock < NEW.quantity THEN
        RAISE EXCEPTION 'Only % left of "%" in stock - please order at most %',
            v_stock, v_name, v_stock;
    END IF;

    UPDATE concession_item
       SET stock_qty = stock_qty - NEW.quantity      -- CHECK (stock_qty >= 0) guards it
     WHERE item_id = NEW.item_id;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_order_item_stock
    BEFORE INSERT ON order_item
    FOR EACH ROW EXECUTE FUNCTION fn_order_item_stock();

