    issued_at      TIMESTAMP NOT NULL DEFAULT now(),
    status         TEXT NOT NULL DEFAULT 'ISSUED' CHECK (status IN ('ISSUED','VOID','USED'))
);
COMMENT ON TABLE ticket IS 'Entrance pass for exactly one booked seat. Cancelling a booking VOIDs its tickets.';

