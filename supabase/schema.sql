CREATE TABLE cancellation_policy (
    policy_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    min_hours_before INTEGER  NOT NULL UNIQUE CHECK (min_hours_before >= 0),
    refund_percent   SMALLINT NOT NULL CHECK (refund_percent BETWEEN 0 AND 100)
);
COMMENT ON TABLE cancellation_policy IS 'Refund tiers: 24h before = 100%, 2h before = 50%, later = 0%.';

-- 10 ------------------------------------------------------------- booking ---
CREATE TABLE booking (
    booking_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  INTEGER NOT NULL REFERENCES customer(customer_id)   ON DELETE RESTRICT,
    screening_id INTEGER NOT NULL REFERENCES screening(screening_id) ON DELETE RESTRICT,
    staff_id     INTEGER          REFERENCES staff(staff_id)         ON DELETE RESTRICT,
    booking_time TIMESTAMP NOT NULL DEFAULT now(),
    status       TEXT NOT NULL DEFAULT 'CONFIRMED' CHECK (status IN ('CONFIRMED','CANCELLED')),
    -- Redundant on purpose: it is the target of the composite FK from
