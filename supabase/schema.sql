-- 11 --------------------------------------------------------- booked_seat ---
CREATE TABLE booked_seat (
    booked_seat_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id     INTEGER NOT NULL,
    screening_id   INTEGER NOT NULL,
