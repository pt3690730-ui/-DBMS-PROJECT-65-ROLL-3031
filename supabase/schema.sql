    method          TEXT NOT NULL CHECK (method IN ('CARD','UPI','CASH','WALLET')),
    status          TEXT NOT NULL DEFAULT 'SUCCESS' CHECK (status IN ('SUCCESS','FAILED','REFUNDED')),
    paid_at         TIMESTAMP NOT NULL DEFAULT now(),
    transaction_ref TEXT NOT NULL UNIQUE,
    CONSTRAINT ck_payment_target CHECK (booking_id IS NOT NULL OR order_id IS NOT NULL)
